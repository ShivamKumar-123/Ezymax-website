// Generates src/components/world-dots.ts: the dotted world map's land dots and projection, precomputed.
// Testing the dot grid against every country polygon in the browser took seconds of main-thread time on each
// page with the map (≈900k spherical point-in-polygon tests); the result never changes, so it ships as data.
// Run after changing W / H / STEP or the atlas: node packages/ui/scripts/gen-world-dots.mjs
import { writeFileSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEqualEarth, geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const W = 960, H = 470, STEP = 7.5;
const land = feature(topo, topo.objects.countries);
const proj = geoEqualEarth().fitSize([W, H], land);
const cols = Math.ceil((W - STEP / 2) / STEP), rows = Math.ceil((H - STEP / 2) / STEP);
// one string per grid row: run lengths alternating sea / land, base-36 digits joined by "."
const out = [];
let count = 0;
for (let j = 0, y = STEP / 2; y < H; j++, y += STEP) {
  const runs = [];
  let cur = false, n = 0;
  for (let i = 0, x = STEP / 2; x < W; i++, x += STEP) {
    const ll = proj.invert([x, y]);
    const on = !!ll && land.features.some((f) => geoContains(f, ll));
    if (on) count++;
    if (on === cur) n++;
    else { runs.push(n); cur = on; n = 1; }
  }
  runs.push(n);
  out.push(runs.map((r) => r.toString(36)).join("."));
}
const [tx, ty] = proj.translate();
const src = `// Generated by packages/ui/scripts/gen-world-dots.mjs — do not edit by hand.
// ${count} land dots of a ${cols}×${rows} grid (step ${STEP}) over a ${W}×${H} Equal Earth map fitted to world-atlas 110m.

export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const WORLD_STEP = ${STEP};
/** geoEqualEarth().fitSize([W, H], land): scale and translate. */
export const WORLD_SCALE = ${proj.scale()};
export const WORLD_TRANSLATE: [number, number] = [${tx}, ${ty}];
/** Per grid row: run lengths (base 36) alternating sea / land, starting with sea. */
export const WORLD_ROWS: readonly string[] = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../src/components/world-dots.ts", import.meta.url), src);
console.log(`${count} dots, ${cols}x${rows} grid, ${src.length} bytes`);

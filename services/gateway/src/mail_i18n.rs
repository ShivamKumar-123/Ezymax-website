//! Language of client-facing transactional emails (verification / sign-in / reset / step-up codes and the welcome
//! email). The Client Area BFF forwards the visitor's `ezymex_locale` cookie as `X-Ezymex-Locale`; the middleware
//! below keeps it in a task-local for the request's lifetime so code paths that send mail can pick it up without
//! threading it through every handler. `Accept-Language` is deliberately ignored: the Back Office never sends
//! `X-Ezymex-Locale`, so staff emails always stay in English.
//!
//! Task-locals do not cross `tokio::spawn`: read `current()` before spawning the send.

use axum::extract::Request;
use axum::middleware::Next;
use axum::response::Response;

tokio::task_local! {
    pub static REQUEST_LOCALE: String;
}

/// Languages the emails are translated into (base subtags).
pub const SUPPORTED: [&str; 22] = [
    "en", "hi", "ar", "ur", "fa", "es", "pt", "fr", "de", "it", "ru", "tr", "id", "ms", "vi", "th", "zh", "ja", "ko", "bn", "ta", "sw",
];

/// Maps a language tag (`pt-BR`, `zh_Hans_CN`, `FR`) to a supported base code; anything else is `en`.
pub fn normalize(raw: &str) -> &'static str {
    let base = raw.trim().split(['-', '_']).next().unwrap_or("").to_ascii_lowercase();
    SUPPORTED.iter().copied().find(|c| *c == base).unwrap_or("en")
}

/// Right-to-left scripts.
pub fn is_rtl(locale: &str) -> bool {
    matches!(normalize(locale), "ar" | "ur" | "fa")
}

/// The locale of the current request (`en` outside a request or without the header).
pub fn current() -> String {
    REQUEST_LOCALE.try_with(|l| l.clone()).unwrap_or_else(|_| "en".to_string())
}

/// Reads `X-Ezymex-Locale` and scopes it over the rest of the request.
pub async fn locale_layer(req: Request, next: Next) -> Response {
    let code = req.headers().get("x-ezymex-locale").and_then(|v| v.to_str().ok()).map(normalize).unwrap_or("en");
    REQUEST_LOCALE.scope(code.to_string(), next.run(req)).await
}

